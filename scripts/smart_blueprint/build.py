def sheet(title, intro, header, rows, widths, start=4, col0=1, ws=None):
    ws = ws or wb.create_sheet(title[:31])
    ws.sheet_view.showGridLines = False
    if intro is not None:
        ws.cell(row=1, column=col0, value=title).font = Font(name=FN, bold=True, size=15, color='1E2329')
        c = ws.cell(row=2, column=col0, value=intro); c.font = Font(name=FN, size=10, color='5B6472'); c.alignment = WR
        ws.merge_cells(start_row=2, start_column=col0, end_row=2, end_column=col0 + len(header) - 1)
        ws.row_dimensions[2].height = max(30, 15 * (1 + len(intro) // 120))
    for j, (h, w) in enumerate(zip(header, widths)):
        c = ws.cell(row=start, column=col0 + j, value=h); c.font = Font(name=FN, bold=True, color='FFFFFF', size=10); c.fill = HF
        c.alignment = Alignment(wrap_text=True, vertical='center'); c.border = BD
        ws.column_dimensions[c.column_letter].width = w
    ws.row_dimensions[start].height = 28
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            c = ws.cell(row=start + 1 + i, column=col0 + j, value=v); c.font = Font(name=FN, size=10); c.alignment = WR; c.border = BD
            if i % 2: c.fill = SF
        longest = max(len(str(v)) / max(widths[j] * 0.9, 1) for j, v in enumerate(row))
        ws.row_dimensions[start + 1 + i].height = min(300, max(20, 15 * (int(longest) + 1)))
    ws.freeze_panes = ws.cell(row=start + 1, column=col0)
    return ws

