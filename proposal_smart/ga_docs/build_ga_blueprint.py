POS = [1]
def sheet(title, intro, header, rows, widths, height=None):
    ws = wb.create_sheet(title[:31], index=POS[0]); POS[0] += 1
    ws.sheet_view.showGridLines = False
    ws['A1'] = title; ws['A1'].font = Font(bold=True, size=14, color='1A2340')
    ws['A2'] = intro; ws['A2'].alignment = WR; ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=max(4, len(header)))
    ws.row_dimensions[2].height = max(30, 15 * (intro.count('\n') + 1 + len(intro) // 160))
    for j, (h, w) in enumerate(zip(header, widths), 1):
        c = ws.cell(row=4, column=j, value=h); c.font = Font(bold=True, color='FFFFFF'); c.fill = HF; c.alignment = Alignment(wrap_text=True, vertical='center'); c.border = BD
        ws.column_dimensions[c.column_letter].width = w
    for i, row in enumerate(rows):
        for j, v in enumerate(row, 1):
            c = ws.cell(row=5 + i, column=j, value=v); c.alignment = WR; c.border = BD
            if i % 2: c.fill = SF
        if height: ws.row_dimensions[5 + i].height = height
    ws.freeze_panes = 'A5'
    return ws

