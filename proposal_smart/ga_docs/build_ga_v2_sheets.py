def write(xlsx, D, prefix='새양식'):
    from openpyxl import load_workbook
    from openpyxl.styles import Font, Alignment, PatternFill, Border, Side
    HF = PatternFill('solid', fgColor='1A2340'); SF = PatternFill('solid', fgColor='EEF2F8')
    thin = Side(style='thin', color='C9CED6'); BD = Border(left=thin, right=thin, top=thin, bottom=thin); WR = Alignment(wrap_text=True, vertical='top')
    wb = load_workbook(xlsx)
    for ws in [w for w in wb.worksheets if w.title.startswith(prefix)]: wb.remove(ws)
    pos = max([i for i, w in enumerate(wb.worksheets) if w.title.startswith('설계도')] or [0]) + 1
    for sh in D['sheets']:
        ws = wb.create_sheet(sh['title'][:31], index=pos); pos += 1
        ws.sheet_view.showGridLines = False
        ws['A1'] = sh['title'] + ' — 새 양식(v2 · GA 최종 시안 2026-11-20)'; ws['A1'].font = Font(bold=True, size=14, color='1A2340')
        ws['A2'] = sh['intro']; ws['A2'].alignment = WR; ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=max(4, len(sh['head'])))
        ws.row_dimensions[2].height = max(30, 15 * (1 + len(sh['intro']) // 110))
        for j, (h, w) in enumerate(zip(sh['head'], sh['widths']), 1):
            c = ws.cell(row=4, column=j, value=h); c.font = Font(bold=True, color='FFFFFF'); c.fill = HF; c.alignment = Alignment(wrap_text=True, vertical='center'); c.border = BD
            ws.column_dimensions[c.column_letter].width = w
        big = len(sh['rows']) > 400
        for i, row in enumerate(sh['rows']):
            for j, v in enumerate(row, 1):
                c = ws.cell(row=5 + i, column=j, value=v)
                if not big: c.alignment = WR; c.border = BD
                if i % 2 and not big: c.fill = SF
        ws.freeze_panes = 'A5'
        if sh['rows']: ws.auto_filter.ref = 'A4:%s%d' % (ws.cell(row=4, column=len(sh['head'])).column_letter, 4 + len(sh['rows']))
    wb.save(xlsx)
    print('시트 %d개 → %s' % (len(D['sheets']), xlsx))

